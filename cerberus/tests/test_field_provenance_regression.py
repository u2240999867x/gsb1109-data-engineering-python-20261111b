# -*- coding: utf-8 -*-
"""
Regression coverage for field-level provenance across the Cerberus lifecycle
``create -> partial update -> re-export``.

One record is replayed from a finite, ordered operation log.  At every write the
test keeps three independent ledgers:

* ``columns``         : columns that actually land in the normalized document
* ``explicit_nulls``  : columns the source submitted with an explicit ``None``
* ``default_filled``  : columns whose value was produced by a schema default,
                        not by the source

Two source histories are constructed so that their normalized artifacts are
byte-identical, while a merge that may only overwrite columns explicitly given
by the source has to treat them differently.  The tests document which
distinctions the current interface preserves and which are gone once a document
has passed through :meth:`~cerberus.Validator.normalized`.
"""

from copy import deepcopy

import pytest

from cerberus import Validator


SCHEMA = {
    'id': {'type': 'integer', 'required': True},
    'status': {'type': 'string', 'default': 'draft'},
    'owner': {'type': 'string', 'default': 'unassigned', 'nullable': True},
    'note': {'type': 'string', 'nullable': True},
    'archived': {'type': 'boolean', 'default': None, 'nullable': True},
}

# A later schema version changes one default. Re-exporting identical stored
# documents must still treat a default-generated column and an explicitly
# submitted one differently.
SCHEMA_V2 = deepcopy(SCHEMA)
SCHEMA_V2['owner']['default'] = 'nobody'

DEFAULT_RULE_FIELDS = {'status', 'owner', 'archived'}

# History A: only id and an explicit null are submitted; every other column is
# generated by schema defaults.
HISTORY_A = (
    ('create', {'id': 1, 'note': None}),
    ('update', {'status': 'published'}),
    ('update', {'owner': None}),
    ('update', {'status': None}),
    ('export', None),
)

# History B: the same target document, but every defaulted value -- including
# ``archived: None``, which equals its default -- is submitted explicitly.
HISTORY_B = (
    (
        'create',
        {
            'id': 1,
            'note': None,
            'status': 'draft',
            'owner': 'unassigned',
            'archived': None,
        },
    ),
    ('update', {'status': 'published'}),
    ('update', {'owner': None}),
    ('update', {'status': None}),
    ('export', None),
)


def normalize(raw):
    return Validator(SCHEMA).normalized(raw)


def source_ledger(raw):
    """Books kept from the raw source payload, before normalization."""
    explicit_nulls = frozenset(field for field, value in raw.items() if value is None)
    default_filled = frozenset(
        field
        for field in DEFAULT_RULE_FIELDS
        if field not in raw
        or (raw.get(field) is None and not SCHEMA[field].get('nullable', False))
    )
    return {
        'columns': frozenset(normalize(raw)),
        'explicit_nulls': explicit_nulls,
        'default_filled': default_filled,
        'given_fields': frozenset(raw),
    }


def changed_columns(before, after):
    return frozenset(
        field for field in after if before.get(field, object()) != after[field]
    )


def merge_naive(stored, raw):
    """Merge using every key of the normalized patch document."""
    result = deepcopy(stored)
    result.update(normalize(raw))
    return result


def merge_with_field_manifest(stored, raw):
    """Merge only source-given columns, taking their normalized values."""
    result = deepcopy(stored)
    normalized_patch = normalize(raw)
    for field in raw:
        result[field] = normalized_patch[field]
    return result


def merge_with_null_marker(stored, raw):
    """Like the manifest merge, but explicit nulls are restored post-normalization."""
    result = deepcopy(stored)
    normalized_patch = normalize(raw)
    for field, value in raw.items():
        result[field] = value if value is None else normalized_patch[field]
    return result


def replay(operations, merge):
    stored = {}
    stages = []
    for kind, payload in operations:
        if kind == 'create':
            stored = normalize(payload)
        elif kind == 'update':
            before = deepcopy(stored)
            stored = merge(stored, payload)
            stages.append(
                {
                    'kind': kind,
                    'payload': deepcopy(payload),
                    'raw_given_fields': frozenset(payload),
                    'normalized_patch_keys': frozenset(normalize(payload)),
                    'changed_columns': changed_columns(before, stored),
                    'stored_after': deepcopy(stored),
                }
            )
        elif kind == 'export':
            stages.append(
                {
                    'kind': kind,
                    'payload': None,
                    'exported_columns': frozenset(normalize(stored)),
                    'stored_before_export': deepcopy(stored),
                }
            )
    return stored, stages


def test_source_ledgers_distinguish_the_two_histories():
    ledger_a = source_ledger(HISTORY_A[0][1])
    ledger_b = source_ledger(HISTORY_B[0][1])

    assert ledger_a['explicit_nulls'] == frozenset({'note'})
    assert ledger_a['default_filled'] == frozenset(
        {'status', 'owner', 'archived'}
    )
    assert ledger_a['given_fields'] == frozenset({'id', 'note'})

    assert ledger_b['explicit_nulls'] == frozenset({'note', 'archived'})
    assert ledger_b['default_filled'] == frozenset()
    assert ledger_b['given_fields'] == frozenset(
        {'id', 'note', 'status', 'owner', 'archived'}
    )


def test_normalized_create_artifacts_are_indistinguishable():
    artifact_a = normalize(HISTORY_A[0][1])
    artifact_b = normalize(HISTORY_B[0][1])

    assert artifact_a == artifact_b
    assert source_ledger(HISTORY_A[0][1]) != source_ledger(HISTORY_B[0][1])


def test_explicit_null_on_nullable_field_without_default_survives():
    # ``note`` is nullable and has no default: presence and null value survive.
    assert normalize({'id': 1, 'note': None})['note'] is None
    # A genuinely missing column stays absent, so null vs missing is kept here.
    assert 'note' not in normalize({'id': 1})


def test_explicit_null_on_nullable_field_with_default_survives():
    # Nullable fields keep an explicit None even though a default exists.
    assert normalize({'owner': None})['owner'] is None


def test_explicit_null_on_nonnullable_default_is_destroyed():
    raw = {'status': None}

    # The raw ledger still records the explicit null ...
    assert source_ledger(raw)['explicit_nulls'] == frozenset({'status'})
    # ... but normalization silently replaces it with the default and books the
    # column as default-filled.
    assert normalize(raw)['status'] == 'draft'
    assert source_ledger(raw)['default_filled'] == frozenset(
        {'status', 'owner', 'archived'}
    )


def test_missing_and_explicit_null_collide_when_default_is_none():
    # ``archived`` has ``default: None``: both inputs normalize to the same doc.
    assert normalize({})['archived'] is None
    assert normalize({'archived': None})['archived'] is None
    assert normalize({}) == normalize({'archived': None})


def test_normalized_patch_leaks_default_columns():
    patch = {'owner': None}
    assert frozenset(patch) == frozenset({'owner'})
    assert frozenset(normalize(patch)) == frozenset(
        {'owner', 'status', 'archived'}
    )


def test_naive_merge_overwrites_columns_the_source_never_mentioned():
    stored, stages = replay(HISTORY_A, merge_naive)

    # Third operation only submits owner, yet the naive merge resets status,
    # which had been changed to 'published' earlier.
    owner_update = stages[1]
    assert owner_update['raw_given_fields'] == frozenset({'owner'})
    assert owner_update['changed_columns'] == frozenset({'owner', 'status'})
    assert stored['status'] == 'draft'


def test_field_manifest_merge_recovers_the_correct_change_set():
    stored, stages = replay(HISTORY_A, merge_with_field_manifest)

    owner_update = stages[1]
    assert owner_update['changed_columns'] == frozenset({'owner'})
    assert owner_update['stored_after']['status'] == 'published'
    assert owner_update['stored_after']['owner'] is None


def test_field_manifest_alone_cannot_recover_destroyed_null():
    stored, stages = replay(HISTORY_A, merge_with_field_manifest)

    # The last update submits status=None; normalization turned it into the
    # default before the merge, so the source intent is already lost.
    status_update = stages[2]
    assert status_update['raw_given_fields'] == frozenset({'status'})
    assert stored['status'] == 'draft'


def test_explicit_null_marker_recovers_the_destroyed_null():
    stored, stages = replay(HISTORY_A, merge_with_null_marker)
    assert stored['status'] is None

    # Re-exporting through normalized() destroys the recovered null again,
    # so the marker has to be carried alongside the stored value.
    export_stage = stages[3]
    assert export_stage['stored_before_export']['status'] is None
    assert normalize(export_stage['stored_before_export'])['status'] == 'draft'


@pytest.mark.parametrize('history', (HISTORY_A, HISTORY_B))
def test_provenance_manifest_keeps_histories_distinguishable(history):
    stored, stages = replay(history, merge_with_null_marker)

    create_manifest = source_ledger(history[0][1])
    if history is HISTORY_A:
        assert create_manifest['given_fields'] == frozenset({'id', 'note'})
        assert create_manifest['default_filled'] == frozenset(
            {'status', 'owner', 'archived'}
        )
    else:
        assert create_manifest['given_fields'] == frozenset(
            {'id', 'note', 'status', 'owner', 'archived'}
        )
        assert create_manifest['default_filled'] == frozenset()

    for stage in stages:
        if stage['kind'] == 'update':
            assert stage['changed_columns'] <= stage['raw_given_fields']

    assert stored['owner'] is None
    assert stored['status'] is None


def reexport(stored, default_filled, schema):
    """Re-export against a (possibly evolved) schema.

    Columns marked as default-generated follow the new schema default; columns
    the source explicitly submitted are left untouched.
    """
    exported = {}
    for field, value in stored.items():
        if field in default_filled and field in schema and 'default' in schema[field]:
            exported[field] = schema[field]['default']
        else:
            exported[field] = value
    return Validator(schema).normalized(exported)


def test_reexport_diverges_once_defaults_evolve():
    # Both histories produced the identical normalized document on create.
    artifact = normalize(HISTORY_A[0][1])
    assert artifact == normalize(HISTORY_B[0][1])

    default_filled_a = source_ledger(HISTORY_A[0][1])['default_filled']
    default_filled_b = source_ledger(HISTORY_B[0][1])['default_filled']

    exported_a = reexport(artifact, default_filled_a, SCHEMA_V2)
    exported_b = reexport(artifact, default_filled_b, SCHEMA_V2)

    # History A let the default own 'owner', so it follows the new default ...
    assert exported_a['owner'] == 'nobody'
    # ... while history B explicitly submitted 'unassigned' and keeps it.
    assert exported_b['owner'] == 'unassigned'

    # A plain re-normalization of the identical artifact cannot make this
    # distinction: both come out the same and the evolved default is ignored.
    assert Validator(SCHEMA_V2).normalized(artifact)['owner'] == 'unassigned'
